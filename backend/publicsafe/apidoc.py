def _needs_admin(route: APIRoute) -> bool:
    stack = list(route.dependant.dependencies)
    while stack:
        dep = stack.pop()
        if dep.call is require_admin:
            return True
        stack.extend(dep.dependencies)
    return False


def _ref_name(schema: dict[str, Any] | None) -> str:
    if not schema:
        return "-"
    if "$ref" in schema:
        return "`" + schema["$ref"].rsplit("/", 1)[-1] + "`"
    if schema.get("type") == "array":
        return "[" + _ref_name(schema.get("items")) + "]"
    if "anyOf" in schema:
        return " or ".join(_ref_name(s) for s in schema["anyOf"])
    return str(schema.get("type", "object"))


def _type(schema: dict[str, Any]) -> str:
    if "$ref" in schema or schema.get("type") == "array" or "anyOf" in schema:
        return _ref_name(schema).replace("`", "")
    if "enum" in schema:
        return " \\| ".join(str(v) for v in schema["enum"])
    return str(schema.get("type", "any"))


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _api_routes() -> dict[tuple[str, str], APIRoute]:
    """Our routers' routes; FastAPI 0.143 hides them behind wrappers in ``app.routes``."""
    from publicsafe.api import (
        auth,
        cameras,
        events,
        health,
        metrics,
        pairing,
        security,
        sessions,
        zones,
    )

    routers = [health.router, auth.router, sessions.router, cameras.router, zones.router,
               security.router, events.router, pairing.admin_router, pairing.public_router,
               metrics.router]  # fmt: skip
    return {
        (method, route.path): route
        for router in routers
        for route in router.routes
        if isinstance(route, APIRoute)
        for method in route.methods
    }


def render(app: FastAPI) -> str:
    spec = app.openapi()
    routes = _api_routes()
    lines = [HEADER, "## REST endpoints", ""]
    by_tag: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            by_tag.setdefault((op.get("tags") or ["other"])[0], []).append((method, path, op))
    for tag in sorted(by_tag):
        if tag == "test":
            continue
        lines += [f"### {tag}", "", "| Method | Path | Auth | Request | Response | Summary |"]
        lines += ["|---|---|---|---|---|---|"]
        for method, path, op in sorted(by_tag[tag], key=lambda x: (x[1], x[0])):
            route = routes[(method.upper(), path)]
            auth = "admin" if _needs_admin(route) else "none"
            params = [p for p in op.get("parameters", []) if p.get("in") == "query"]
            request = ""
            if params:
                request = "query: " + ", ".join(
                    p["name"] + ("" if p.get("required") else "?") for p in params
                )
            body = op.get("requestBody", {}).get("content", {}).get("application/json")
            if body:
                request = (request + "; " if request else "") + _ref_name(body.get("schema"))
            responses = []
            for code, resp in sorted(op.get("responses", {}).items()):
                if code == "422":
                    continue  # FastAPI's default; this app answers 400 validation_error
                content = resp.get("content", {})
                if "application/json" in content:
                    responses.append(
                        f"{code} {_ref_name(content['application/json'].get('schema'))}"
                    )
                elif content:
                    responses.append(f"{code} {next(iter(content))}")
                else:
                    responses.append(code)
            summary = _cell(op.get("description") or op.get("summary") or "").split(". ")[0]
            lines.append(
                f"| {method.upper()} | `{path}` | {auth} | {_cell(request) or '-'} | "
                f"{_cell(', '.join(responses))} | {summary} |"
            )
        lines.append("")

    lines += ["## Schemas", ""]
    for name, schema in sorted(spec.get("components", {}).get("schemas", {}).items()):
        if name in ("HTTPValidationError", "ValidationError"):
            continue
        props = schema.get("properties", {})
        if not props:
            continue
        required = set(schema.get("required", []))
        lines += [f"### `{name}`", ""]
        if schema.get("description"):
            lines += [_cell(schema["description"]), ""]
        lines += ["| Field | Type | Required |", "|---|---|---|"]
        for field, sub in props.items():
            lines.append(
                f"| `{field}` | {_cell(_type(sub))} | {'yes' if field in required else ''} |"
            )
        lines.append("")
    lines.append(WEBSOCKETS)
    return "\n".join(lines).rstrip() + "\n"


def render_default() -> str:
    """Build a throw-away app (temp SQLite, no TEST_MODE) and render its API."""
    from argon2 import PasswordHasher

    from publicsafe.config import Settings
    from publicsafe.main import create_app

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        settings = Settings(
            _env_file=None,  # type: ignore[call-arg]
            admin_password_hash=PasswordHasher(time_cost=1, memory_cost=8 * 1024).hash("x" * 12),
            database_url=f"sqlite+pysqlite:///{root / 'api.db'}",
            data_dir=root / "data",
            frontend_dist=root / "no-dist",
            detector="none",
            test_mode=False,
            log_level="WARNING",
        )
        app = create_app(settings)
        text = render(app)
        app.state.engine.dispose()
        return text

"""``docs/API.md``: the REST part generated from the app's OpenAPI schema, plus the WebSocket tables.

``publicsafe api-docs`` writes the file, ``publicsafe api-docs --check`` (and
``tests/unit/test_apidoc.py``) fail when it no longer matches the code. The
WebSocket tables are written by hand below because OpenAPI cannot describe
them; they follow ``ws/camera.py``, ``ws/dashboard.py`` and ``ws/hub.py``.
"""

from __future__ import annotations

import tempfile
from pathlib import Path
from typing import Any

from fastapi import FastAPI
from fastapi.routing import APIRoute

from publicsafe.api.deps import require_admin

HEADER = """# public.safe API reference

Generated by `publicsafe api-docs` from the FastAPI OpenAPI schema (REST) and
the WebSocket handlers; do not edit by hand. The live schema is served at
`/api/openapi.json` and browsable at `/api/docs`.

## Conventions

- Base URL `https://<host>:8443`. JSON bodies, timestamps ISO-8601 UTC with
  milliseconds.
- **Admin** routes need the `ps_admin` session cookie (from
  `POST /api/auth/login`) and, on every non-GET request, the header
  `X-Requested-With: publicsafe` (CSRF check).
- **Device** authentication happens only inside the `/ws/camera` `auth`
  message; device tokens never appear in URLs or headers.
- Every response carries `X-Request-ID` (a client may send its own, up to 64
  characters of `[A-Za-z0-9._-]`); the same id is in the server's JSON logs.
- Errors always have one shape:
  `{"error": {"code": "pin_invalid", "message": "...", "details": {}}}`.
  400 validation (`validation_error`, `details.fields`), 401 unauthenticated,
  403 forbidden / CSRF, 404 not found, 409 conflict, 410 gone, 423 locked,
  429 rate limited (with `Retry-After`), 500 internal (no stack trace).
- `TEST_MODE=1` adds `/api/test/*` (Playwright and fake-phone tests only); those
  routes are not listed here.
"""

